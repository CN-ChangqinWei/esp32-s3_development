# ============================================================================
# ESP32-C3 flash helper (ASCII only: Windows PowerShell 5.1 reads .ps1 as ANSI)
#
# Why this script exists:
#   This board uses the ESP32-C3 native USB-Serial/JTAG (VID_303A&PID_1001).
#   esptool's default "--before default_reset" makes the USB device re-enumerate,
#   so the port disappears while esptool is opening it -> IDE reports
#   "could not open port" / "port not detected". Verified workaround:
#   "--before usb_reset".
#
#   NOTE: idf.py flash --extra-args cannot be used for this, because extra args
#   are appended AFTER the "write_flash" subcommand while --before/--after are
#   GLOBAL esptool options (must precede the subcommand). So this script calls
#   esptool directly and reuses build/flash_args generated by idf.py.
#
# Usage:
#   .\scripts\flash.ps1                  # auto pick first COM port
#   .\scripts\flash.ps1 -Port COM11
#   .\scripts\flash.ps1 -Build           # build then flash
#   .\scripts\flash.ps1 -Erase           # erase whole flash first
#   .\scripts\flash.ps1 -Monitor         # prompt to press REST, then monitor
#   .\scripts\flash.ps1 -NoUsbReset      # fall back to plain idf.py flash (CH340)
# ============================================================================
param(
    [string]$Port = "",
    [switch]$Build,
    [switch]$Erase,
    [switch]$Monitor,
    [switch]$NoUsbReset,
    [int]$Baud = 460800
)

$ErrorActionPreference = 'Stop'

$env:IDF_PATH       = 'E:\esp32-idf\v5.5.3\esp-idf'
$env:IDF_TOOLS_PATH = 'E:\esp32-idf_tools'
$Python             = Join-Path $env:IDF_TOOLS_PATH 'python_env\idf5.5_py3.11_env\Scripts\python.exe'

if (-not (Test-Path $Python)) { throw "IDF python not found: $Python" }

if (-not $Port) {
    $ports = [System.IO.Ports.SerialPort]::GetPortNames()
    if (-not $ports -or $ports.Count -eq 0) {
        throw "No serial port found. Check USB cable (data-capable) and power."
    }
    $Port = $ports[0]
    if ($ports.Count -gt 1) {
        Write-Host "[flash] multiple ports: $($ports -join ', '), using $Port"
    }
}

Write-Host "[flash] port=$Port idf=$env:IDF_PATH"

# Load ESP-IDF environment (cmake / ninja / toolchain).
# NOTE: export.ps1 prints progress to stderr; PowerShell 5.1 turns native stderr
# into NativeCommandError which is terminating while ErrorActionPreference=Stop.
# We temporarily relax it and swallow stderr. The flash path itself only needs
# the venv python + esptool, so export failing must not abort the script.
$prevEap = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
try { . "$env:IDF_PATH\export.ps1" 2>$null | Out-Null } catch { Write-Host "[flash] warning: export.ps1 failed, continue" }
$ErrorActionPreference = $prevEap

# Repo root = parent of this script's folder
$repoRoot = Split-Path $PSScriptRoot -Parent
Set-Location $repoRoot

if ($Build) {
    Write-Host "[flash] building..."
    idf.py build
    if ($LASTEXITCODE -ne 0) { throw "build failed" }
}

if ($NoUsbReset) {
    Write-Host "[flash] falling back to: idf.py flash"
    if ($Erase) { idf.py -p $Port erase-flash }
    idf.py -p $Port flash
    if ($LASTEXITCODE -ne 0) { throw "flash failed" }
    Write-Host "[flash] done."
    exit 0
}

$buildDir = Join-Path $repoRoot 'build'
$flashArgsPath = Join-Path $buildDir 'flash_args'
if (-not (Test-Path $flashArgsPath)) {
    throw "build/flash_args not found. Run with -Build first."
}

$lines = Get-Content $flashArgsPath | Where-Object { $_.Trim() -ne '' }
$optTokens = $lines[0].Trim() -split '\s+'
$pairs = @()
for ($i = 1; $i -lt $lines.Count; $i++) {
    $pairs += ($lines[$i].Trim() -split '\s+')
}

Push-Location $buildDir
try {
    if ($Erase) {
        Write-Host "[flash] erasing flash (usb_reset)..."
        & $Python -m esptool --chip esp32c3 --port $Port --before usb_reset erase_flash
        if ($LASTEXITCODE -ne 0) { throw "erase failed" }
    }

    Write-Host "[flash] flashing (usb_reset + no_reset)..."
    & $Python -m esptool --chip esp32c3 --port $Port --baud $Baud `
        --before usb_reset --after no_reset `
        write_flash @optTokens @pairs
    if ($LASTEXITCODE -ne 0) { throw "flash failed" }
}
finally {
    Pop-Location
}

Write-Host "[flash] done. Press REST on the board to run the new firmware."

if ($Monitor) {
    Read-Host "Press Enter to start monitor (Ctrl+] to exit)" | Out-Null
    idf.py -p $Port monitor
}
